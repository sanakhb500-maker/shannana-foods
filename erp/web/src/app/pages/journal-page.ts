import { DecimalPipe } from '@angular/common';
import { Component, OnInit, computed, inject, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { Observable } from 'rxjs';
import { Api, parseApiError } from '../core/api';
import { Auth } from '../core/auth';
import { I18n } from '../core/i18n';
import { AccountDto, JournalEntry, JournalLine, JournalRow, Paged, WRITE_ROLES } from '../core/models';

const today = () => new Date().toISOString().slice(0, 10);
const SOURCES = ['Manual', 'GoodsReceipt', 'PurchaseInvoice', 'SupplierPayment', 'DeliveryNote', 'SalesInvoice', 'SalesReturn', 'CustomerReceipt', 'StockAdjustment'];

/**
 * The general journal. Manual entries are drafted, posted and reversed here; entries generated by documents
 * (receipts, invoices, deliveries...) are shown read-only and are undone by cancelling the document.
 */
@Component({
  selector: 'app-journal-page',
  imports: [FormsModule, DecimalPipe],
  template: `
    <header class="page-head">
      <h1>{{ i18n.t('nav.journal') }}</h1>
      <div class="page-tools">
        <select class="input" [(ngModel)]="source" (ngModelChange)="reload()">
          <option value="">{{ i18n.t('acc.allSources') }}</option>
          @for (s of sources; track s) {
            <option [value]="s">{{ i18n.t('src.' + s) }}</option>
          }
        </select>
        <select class="input" [(ngModel)]="status" (ngModelChange)="reload()">
          <option value="">{{ i18n.t('inv.allStatuses') }}</option>
          @for (s of statuses; track s) {
            <option [value]="s">{{ i18n.t('je.' + s) }}</option>
          }
        </select>
        <input class="input date" type="date" [(ngModel)]="from" (ngModelChange)="reload()" [title]="i18n.t('inv.from')" />
        <input class="input date" type="date" [(ngModel)]="to" (ngModelChange)="reload()" [title]="i18n.t('inv.to')" />
        @if (canWrite) {
          <button class="btn primary" type="button" (click)="openNew()">+ {{ i18n.t('acc.newEntry') }}</button>
        }
      </div>
    </header>

    @if (message() && !entry()) {
      <div class="alert error">{{ message() }}</div>
    }

    <div class="card table-wrap">
      <table class="table">
        <thead>
          <tr>
            <th>{{ i18n.t('inv.number') }}</th>
            <th>{{ i18n.t('f.date') }}</th>
            <th>{{ i18n.t('f.description') }}</th>
            <th>{{ i18n.t('acc.source') }}</th>
            <th class="num">{{ i18n.t('inv.value') }}</th>
            <th>{{ i18n.t('common.status') }}</th>
          </tr>
        </thead>
        <tbody>
          @for (r of rows(); track r.id) {
            <tr class="clickable" (click)="open(r.id)">
              <td>{{ r.number }}</td>
              <td>{{ r.date }}</td>
              <td>{{ r.description }}</td>
              <td>{{ i18n.t('src.' + r.sourceType) }}</td>
              <td class="num">{{ r.total | number: '1.2-2' }}</td>
              <td><span class="badge" [class.ok]="r.status === 'Posted'" [class.muted]="r.status === 'Reversed'">{{ i18n.t('je.' + r.status) }}</span></td>
            </tr>
          } @empty {
            <tr><td class="empty" colspan="6">{{ i18n.t(loading() ? 'common.loading' : 'common.empty') }}</td></tr>
          }
        </tbody>
      </table>
    </div>

    <footer class="pager">
      <span>{{ i18n.t('common.total') }}: {{ total() }}</span>
      <span class="spacer"></span>
      <button class="btn sm" type="button" [disabled]="page() <= 1" (click)="go(-1)">{{ i18n.t('common.prev') }}</button>
      <span>{{ page() }} / {{ pages() }}</span>
      <button class="btn sm" type="button" [disabled]="page() >= pages()" (click)="go(1)">{{ i18n.t('common.next') }}</button>
    </footer>

    @if (entry(); as e) {
      <div class="modal-backdrop" (click)="close()">
        <form class="modal wide-modal card" (click)="$event.stopPropagation()" (ngSubmit)="save()" novalidate>
          <h2>
            {{ i18n.t('nav.journal') }} {{ e.number ?? '' }}
            <span class="badge" [class.ok]="e.status === 'Posted'" [class.muted]="e.status === 'Reversed'">{{ i18n.t('je.' + e.status) }}</span>
            @if (!isManual()) { <span class="badge">{{ i18n.t('src.' + e.sourceType) }}</span> }
          </h2>

          @if (message()) {
            <div class="alert error">{{ message() }}</div>
          }
          @if (!isManual()) {
            <p class="hint-text">{{ i18n.t('acc.generatedHint') }}</p>
          }

          <div class="form-grid">
            <div class="field">
              <label for="j-date">{{ i18n.t('f.date') }} <span class="req">*</span></label>
              <input id="j-date" class="input" type="date" name="date" [(ngModel)]="e.date" [disabled]="!editable()" />
            </div>
            <div class="field">
              <label for="j-desc">{{ i18n.t('f.description') }} <span class="req">*</span></label>
              <input id="j-desc" class="input" name="description" [(ngModel)]="e.description" maxlength="300" [disabled]="!editable()" />
            </div>
          </div>

          <div class="table-wrap lines">
            <table class="table">
              <thead>
                <tr>
                  <th>{{ i18n.t('acc.account') }}</th>
                  <th class="num">{{ i18n.t('pur.debit') }}</th>
                  <th class="num">{{ i18n.t('pur.credit') }}</th>
                  <th>{{ i18n.t('f.description') }}</th>
                  @if (editable()) { <th></th> }
                </tr>
              </thead>
              <tbody>
                @for (l of e.lines; track $index; let i = $index) {
                  <tr>
                    <td>
                      <select class="input" [name]="'acc' + i" [(ngModel)]="l.accountId" [disabled]="!editable()">
                        <option [ngValue]="0" disabled>{{ i18n.t('common.select') }}</option>
                        @for (a of accountChoices(l.accountId); track a.id) {
                          <option [ngValue]="a.id">{{ label(a) }}</option>
                        }
                      </select>
                    </td>
                    <td class="num"><input class="input qty" type="number" step="0.0001" min="0" [name]="'dr' + i" [(ngModel)]="l.debit" (ngModelChange)="l.credit = l.debit ? null : l.credit" [disabled]="!editable()" /></td>
                    <td class="num"><input class="input qty" type="number" step="0.0001" min="0" [name]="'cr' + i" [(ngModel)]="l.credit" (ngModelChange)="l.debit = l.credit ? null : l.debit" [disabled]="!editable()" /></td>
                    <td><input class="input" [name]="'ds' + i" [(ngModel)]="l.description" maxlength="200" [disabled]="!editable()" /></td>
                    @if (editable()) {
                      <td class="actions"><button class="btn sm danger" type="button" (click)="removeLine(i)" [attr.aria-label]="i18n.t('common.remove')">✕</button></td>
                    }
                  </tr>
                }
              </tbody>
              <tfoot>
                <tr>
                  <th>{{ i18n.t('common.total') }}</th>
                  <th class="num">{{ totalOf('debit') | number: '1.2-4' }}</th>
                  <th class="num">{{ totalOf('credit') | number: '1.2-4' }}</th>
                  <th [class.neg]="!balanced()" [class.pos]="balanced()">{{ i18n.t(balanced() ? 'acc.balanced' : 'acc.unbalanced') }}</th>
                  @if (editable()) { <th></th> }
                </tr>
              </tfoot>
            </table>
          </div>
          @if (editable()) {
            <button class="btn sm" type="button" (click)="addLine()">+ {{ i18n.t('inv.addLine') }}</button>
          }

          <div class="modal-actions">
            <button class="btn" type="button" (click)="close()">{{ i18n.t('common.close') }}</button>
            @if (canWrite && isManual() && e.status === 'Draft') {
              @if (e.id) { <button class="btn danger" type="button" [disabled]="busy()" (click)="remove()">{{ i18n.t('acc.deleteDraft') }}</button> }
              <button class="btn" type="submit" [disabled]="busy()">{{ i18n.t('common.save') }}</button>
              <button class="btn primary" type="button" [disabled]="busy()" (click)="post()">{{ i18n.t('acc.post') }}</button>
            }
            @if (canWrite && isManual() && e.status === 'Posted' && !e.reversalOfId) {
              <button class="btn danger" type="button" [disabled]="busy()" (click)="reverse()">{{ i18n.t('acc.reverse') }}</button>
            }
          </div>
        </form>
      </div>
    }
  `,
})
export class JournalPage implements OnInit {
  private readonly api = inject(Api);
  private readonly auth = inject(Auth);
  readonly i18n = inject(I18n);

  readonly canWrite = this.auth.hasAnyRole(WRITE_ROLES.accounting);
  readonly sources = SOURCES;
  readonly statuses = ['Draft', 'Posted', 'Reversed'];
  readonly rows = signal<JournalRow[]>([]);
  readonly total = signal(0);
  readonly page = signal(1);
  readonly pages = computed(() => Math.max(1, Math.ceil(this.total() / 20)));
  readonly loading = signal(false);
  readonly message = signal('');
  readonly entry = signal<JournalEntry | null>(null);
  readonly busy = signal(false);
  readonly accounts = signal<AccountDto[]>([]);
  source = '';
  status = '';
  from = '';
  to = '';

  readonly isManual = computed(() => (this.entry()?.sourceType ?? 'Manual') === 'Manual');
  readonly editable = computed(() => this.canWrite && this.isManual() && this.entry()?.status === 'Draft');

  ngOnInit(): void {
    this.api.list<AccountDto>('accounts', { pageSize: 500 }).subscribe((r) => this.accounts.set(r.items));
    this.load();
  }

  label(a: AccountDto): string {
    return `${a.code} — ${this.i18n.name(a)}`;
  }

  accountChoices(selected: number): AccountDto[] {
    return this.accounts().filter((a) => (a.isActive && a.isPostable) || a.id === selected);
  }

  reload(): void {
    this.page.set(1);
    this.load();
  }

  go(d: number): void {
    this.page.update((p) => Math.min(this.pages(), Math.max(1, p + d)));
    this.load();
  }

  private load(): void {
    this.loading.set(true);
    const qs = [`page=${this.page()}`, 'pageSize=20'];
    if (this.source) qs.push(`sourceType=${this.source}`);
    if (this.status) qs.push(`status=${this.status}`);
    if (this.from) qs.push(`from=${this.from}`);
    if (this.to) qs.push(`to=${this.to}`);
    this.api.get<Paged<JournalRow>>(`journalentries?${qs.join('&')}`).subscribe({
      next: (r) => {
        this.rows.set(r.items);
        this.total.set(r.total);
        this.loading.set(false);
      },
      error: (e) => {
        this.message.set(parseApiError(e).message);
        this.loading.set(false);
      },
    });
  }

  openNew(): void {
    this.message.set('');
    this.entry.set({
      date: today(), description: '', status: 'Draft', sourceType: 'Manual',
      lines: [{ accountId: 0, debit: null, credit: null, description: null }, { accountId: 0, debit: null, credit: null, description: null }],
    });
  }

  open(id: number): void {
    this.message.set('');
    this.api.get<JournalEntry>(`journalentries/${id}`).subscribe({
      next: (e) => this.entry.set(e),
      error: (e) => this.message.set(parseApiError(e).message),
    });
  }

  close(): void {
    this.entry.set(null);
  }

  addLine(): void {
    this.entry()?.lines.push({ accountId: 0, debit: null, credit: null, description: null });
  }

  removeLine(i: number): void {
    this.entry()?.lines.splice(i, 1);
  }

  totalOf(side: 'debit' | 'credit'): number {
    return (this.entry()?.lines ?? []).reduce((s, l: JournalLine) => s + Number(l[side] ?? 0), 0);
  }

  balanced(): boolean {
    return Math.abs(this.totalOf('debit') - this.totalOf('credit')) < 0.00005 && this.totalOf('debit') > 0;
  }

  private body() {
    const e = this.entry()!;
    return {
      date: e.date,
      description: e.description?.trim() ?? '',
      lines: e.lines.map((l) => ({
        accountId: l.accountId,
        debit: Number(l.debit ?? 0),
        credit: Number(l.credit ?? 0),
        description: l.description?.trim() || null,
      })),
    };
  }

  private errorText(err: unknown): string {
    const p = parseApiError(err);
    const detail = Object.values(p.fields).flat().join(' ');
    return detail ? `${p.message} ${detail}` : p.message;
  }

  private run(call: () => Observable<JournalEntry | unknown>, closeAfter = false): void {
    this.busy.set(true);
    this.message.set('');
    call().subscribe({
      next: (e) => {
        this.busy.set(false);
        if (closeAfter) this.entry.set(null);
        else this.entry.set(e as JournalEntry);
        this.load();
      },
      error: (err) => {
        this.message.set(this.errorText(err));
        this.busy.set(false);
      },
    });
  }

  private saveCall(): Observable<JournalEntry> {
    const e = this.entry()!;
    return e.id ? this.api.update<JournalEntry>('journalentries', e.id, this.body()) : this.api.create<JournalEntry>('journalentries', this.body());
  }

  save(): void {
    if (this.editable()) this.run(() => this.saveCall());
  }

  /** Saves the draft first, then posts it. */
  post(): void {
    this.busy.set(true);
    this.message.set('');
    this.saveCall().subscribe({
      next: (saved) => {
        this.busy.set(false);
        this.entry.set(saved);
        this.run(() => this.api.post<JournalEntry>(`journalentries/${saved.id}/post`));
      },
      error: (err) => {
        this.message.set(this.errorText(err));
        this.busy.set(false);
      },
    });
  }

  remove(): void {
    const id = this.entry()?.id;
    if (!id || !confirm(this.i18n.t('inv.confirmCancel'))) return;
    this.run(() => this.api.deactivate('journalentries', id), true);
  }

  reverse(): void {
    const id = this.entry()?.id;
    if (!id || !confirm(this.i18n.t('acc.confirmReverse'))) return;
    this.run(() => this.api.post<JournalEntry>(`journalentries/${id}/reverse`), true);
  }
}
